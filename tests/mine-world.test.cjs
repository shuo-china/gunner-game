const test = require('node:test');
const assert = require('node:assert/strict');
const { CombatWorld, MinePlacement, createMineDefinition, createMineOre, minePerlinNoise, MINE_MAP,
  getWeapon, DecimalAmount: D } = require('./.build/core/index.js');
const { ECONOMY_CONFIG } = require('./.build/core/EconomyConfig.js');

function battle(type = 'SINGLE', rare = true) {
  const ore = createMineOre(0, { x: -100, z: 30 }, rare);
  const stage = { ...new MinePlacement(42).stage, ores: [ore] };
  const world = new CombatWorld(31, stage);
  world.setLoadout([{ actorIndex: 0, weapon: { ...getWeapon(0), type, explosionRadius: 8, missileExplosionRadius: 8,
    blastSniperExplosionRadius: 8, pelletCount: 3, shotgunSpreadAngle: 0, missileSpeed: 35 },
    damage: D.from('1e100'), criticalChance: 1, criticalMultiplier: 100, attackInterval: .6 }]);
  world.player.aim = { x: 0, z: 1 }; world.player.targetId = ore.id;
  world.nearHitPoint = { ...ore.position }; world.setMuzzleOffset({ x: 0, z: 0 });
  return { ore, world };
}

test('Mine Perlin matches shipped libunity ARM64 samples bit-for-bit', () => {
  // Native wrapper 0x529748 / kernel 0xd9c308, run with Unicorn ARM64.
  // Values are native outputs, not fixtures generated by the port.
  for (const [x, y, expected] of [[0, 0, .46527308225631714], [.1, .2, .4956870973110199],
    [-.1, .2, .4956870973110199], [23.462, 64.981, .12628675997257233],
    [2000.2, 9999.33, .2846511900424957], [.5, .5, .29669588804244995], [1.25, -3.75, .3243710696697235]]) {
    assert.equal(minePerlinNoise(x, y), expected, `${x},${y}`);
  }
});

test('Mine sampling yields after each 30 annulus candidates and activates the real pool in batches', () => {
  const placement = new MinePlacement(42); let previous = placement.snapshot(), calls = 0;
  assert.equal(placement.ready, false); assert.equal(placement.stage.ores.length, 0);
  while (!placement.ready) {
    const next = placement.advanceFrame(); calls++;
    if (next.phase === 'sampling') assert.equal(next.processedCandidates - previous.processedCandidates, 30);
    if (previous.phase === 'placing' && next.phase === 'placing') assert.ok(next.placed - previous.placed <= 30);
    assert.ok(calls < 300); previous = next;
  }
  let cells = 0;
  for (let x = -148; x <= 148; x += 4) for (let z = -148; z <= 148; z += 4)
    if (x*x + z*z >= MINE_MAP.innerRadius ** 2 && x*x + z*z <= 150 ** 2) cells++;
  assert.equal(previous.processedCandidates, cells);
  assert.equal(calls, Math.floor(cells / 30) + Math.floor(1000 / 30) + 1);
  assert.equal(previous.total, placement.stage.ores.length); assert.equal(previous.placed, previous.total);
  assert.deepEqual(placement.advanceFrame(), previous, 'ready placement is idempotent');
  const stage = placement.stage;
  assert.equal(stage.mapLayout, 'mine'); assert.deepEqual(stage.spawnPosition, { x: -100, z: 0 });
  assert.deepEqual(stage.trees, []); assert.deepEqual(stage.bulletWalls, []);
  assert.equal(stage.ores.length, 1000); assert.equal(stage.ores.filter(ore => ore.rare).length, ECONOMY_CONFIG.mine.rareOreCount);
  assert.deepEqual(stage, createMineDefinition(42)); assert.notDeepEqual(stage.ores, createMineDefinition(43).ores);
  for (const ore of stage.ores) {
    const radius = Math.hypot(ore.position.x + 100, ore.position.z);
    assert.ok(radius >= MINE_MAP.innerRadius && radius <= 150);
    assert.equal(Math.abs((ore.position.x + 100) % 4), 0); assert.equal(Math.abs(ore.position.z % 4), 0);
    assert.equal(ore.health.toString(), ore.rare ? '5' : '3');
    assert.equal(ore.score, ore.rare ? ECONOMY_CONFIG.mine.rareScore : ECONOMY_CONFIG.mine.normalScore);
    assert.equal(ore.colliderMinY, 0); assert.equal(ore.colliderMaxY, 4);
  }
});

test('all seven weapon routes apply literal 1 ore damage even to enormous retained critical bullets', () => {
  for (const type of ['SINGLE', 'LASER', 'PIERCE', 'SHOTGUN', 'EXPLOSIVE', 'MISSILE', 'BLAST_SNIPER']) {
    const { ore, world } = battle(type); world.spread = 0; assert.equal(world.fire(), true);
    for (const bullet of world.bullets) if (bullet.damaging) bullet.critical = true;
    if (type === 'MISSILE') world.updateMissiles(2); else world.updateBullets(.7);
    const events = world.drainEvents(), hits = events.filter(e => e.type === 'hit');
    assert.equal(hits.length, type === 'SHOTGUN' ? 3 : 1, type);
    assert.equal(ore.health.toString(), type === 'SHOTGUN' ? '2' : '4', type);
    assert.ok(hits.every(e => e.damage.compare(1) === 0 && e.critical === false), type);
    assert.equal(events.some(e => ['damageText', 'treeDied', 'bossDied', 'complete'].includes(e.type)), false, type);
  }
});

test('Mine deaths score once, never respawn or finish the main wave, and reject timeout contacts', () => {
  const { ore, world } = battle('SINGLE', false);
  for (let hit = 0; hit < 20; hit++) world.hitTree(ore, ore.position, D.from('1e100'));
  let events = world.drainEvents();
  assert.equal(ore.health.toString(), '0'); assert.equal(ore.alive, false); assert.equal(world.stats.kills, 1);
  assert.equal(events.filter(e => e.type === 'hit').length, 3);
  assert.deepEqual(events.filter(e => e.type === 'oreDied'), [{ type: 'oreDied', position: ore.position,
    oreId: ore.id, score: ECONOMY_CONFIG.mine.normalScore, sourceTime: 0 }]);
  assert.equal(world.stats.complete, false); assert.equal(world.damageTargets[0], ore); assert.deepEqual(world.trees, []);
  for (let frame = 0; frame < 600; frame++) world.step(.1);
  assert.equal(ore.alive, false); assert.equal(world.stage.ores.length, 1); assert.deepEqual(world.drainEvents(), []);
  const other = battle(); other.world.stopCombat(); other.world.hitTree(other.ore, other.ore.position, D.from(999));
  assert.equal(other.ore.health.toString(), '5');
  const late = other.world.drainEvents();
  assert.equal(late.length, 1); assert.equal(late[0].type, 'damageText');
  assert.equal(late[0].damage.toString(), '1'); assert.equal(late[0].critical, false);
});

test('Mine fallback targets the nearest active ore in XZ and preserves original pool order for ties', () => {
  const { world } = battle();
  const near = createMineOre(5, { x: -100, z: 45 }), fartherBehind = createMineOre(2, { x: -146, z: 0 });
  world.stage.ores.splice(0, world.stage.ores.length, fartherBehind, near);
  assert.equal(world.findAutoTarget(), near, 'forward ore has no Main Z weighting');
  const tie = createMineOre(1, { x: -55, z: 0 }); world.stage.ores.unshift(tie);
  assert.equal(world.findAutoTarget(), tie, 'equal distance keeps pool array order, not numeric ID');
  tie.alive = false; assert.equal(world.findAutoTarget(), near);
  near.alive = fartherBehind.alive = false; assert.equal(world.findAutoTarget(), undefined);
});
