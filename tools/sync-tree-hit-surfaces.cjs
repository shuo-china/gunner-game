const fs = require('node:fs');
const path = require('node:path');
const { pngAlpha } = require('./lib/png-alpha.cjs');
const root = path.resolve(__dirname, '..');

// Sparse, opaque scanlines retain holes in the artwork. Store pixel coordinates
// so the runtime uses the exact same dimensions, pivot and scale as the sprite.
function surfaces() {
  const config = JSON.parse(fs.readFileSync(path.join(root, 'assets/resources/art/stages/config.json'), 'utf8'));
  const result = {};
  for (const sprite of config.treeSprites) {
    const png = pngAlpha(fs.readFileSync(path.join(root, 'assets/resources', sprite.path + '.png')), 128);
    const rows = [], step = Math.max(1, Math.floor(png.height / 48));
    for (let y = 0; y < png.height; y += step) {
      const row = [y]; let start = -1;
      for (let x = 0; x <= png.width; x++) {
        const opaque = x < png.width && png.at(x, y) >= 128;
        if (opaque && start < 0) start = x;
        if (!opaque && start >= 0) { row.push(start, x - 1); start = -1; }
      }
      if (row.length > 1) rows.push(row);
    }
    result[sprite.path] = { width: png.width, height: png.height, rows };
  }
  return result;
}
function source() {
  const data = surfaces();
  return '// Generated by node tools/sync-tree-hit-surfaces.cjs --write after changing stage artwork.\n' +
    'export const TREE_HIT_SURFACES: Record<string, { width: number; height: number; rows: number[][] }> = {\n' +
    Object.entries(data).map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`).join('\n') + '\n};\n';
}
if (require.main === module) {
  const target = path.join(root, 'assets/scripts/view/TreeHitSurfaceData.ts'), expected = source();
  if (process.argv.includes('--write')) fs.writeFileSync(target, expected);
  else if (fs.readFileSync(target, 'utf8') !== expected) throw new Error('Stale tree hit surfaces; run node tools/sync-tree-hit-surfaces.cjs --write');
}
module.exports = { surfaces, source };
