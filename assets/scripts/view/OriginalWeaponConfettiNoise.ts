const primeX=501125321,primeY=1136930381;
function grad(seed:number,i:number,j:number,x:number,y:number):number {
  let hash=Math.imul(seed^i^j,0x27d4eb2d);hash^=hash>>15;hash&=254;
  return x*gradients[hash]+y*gradients[hash|1];
}
export function originalConfettiNoise(x:number,y:number,frequency:number,seed=1337):number {
  x*=frequency;y*=frequency;
  const sqrt3=Math.sqrt(3),g=(3-sqrt3)/6,skew=(x+y)*.5*(sqrt3-1);x+=skew;y+=skew;
  const floor=(v:number)=>v>=0?Math.trunc(v):Math.trunc(v)-1;
  let i=floor(x),j=floor(y);const xi=x-i,yi=y-j,t=(xi+yi)*g,x0=xi-t,y0=yi-t;
  i=Math.imul(i,primeX);j=Math.imul(j,primeY);
  const a=.5-x0*x0-y0*y0;
  const n0=a<=0?0:a*a*a*a*grad(seed,i,j,x0,y0);
  const c=2*(1-2*g)*(1/g-2)*t+(-2*(1-2*g)*(1-2*g)+a);
  const x2=x0+2*g-1,y2=y0+2*g-1;
  const n2=c<=0?0:c*c*c*c*grad(seed,(i+primeX)|0,(j+primeY)|0,x2,y2);
  const upper=y0>x0,x1=x0+(upper?g:g-1),y1=y0+(upper?g-1:g),b=.5-x1*x1-y1*y1;
  const n1=b<=0?0:b*b*b*b*grad(seed,(i+(upper?0:primeX))|0,(j+(upper?primeY:0))|0,x1,y1);
  return (n0+n1+n2)*99.83685446303647;
}
